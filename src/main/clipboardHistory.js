// Clipboard history: "what did I copy earlier?". Text only, kept in memory only (never written to disk, gone when Relay quits), for a day by default.
// It never keeps what a password manager marks as secret, and skips anything that looks like a password, a key, a card number or a social security
// number, so those are never recorded in the first place. No Electron in here: the clipboard is read through a function the app gives it.

const CONCEALED = ['org.nspasteboard.ConcealedType', 'org.nspasteboard.TransientType', 'org.nspasteboard.AutoGeneratedType', 'com.agilebits.onepassword', 'de.petermaurer.TransientPasteboardType', 'net.antelle.keeweb'];

const luhn = (digits) => { let sum = 0; let alt = false; for (let i = digits.length - 1; i >= 0; i--) { let n = +digits[i]; if (alt) { n *= 2; if (n > 9) n -= 9; } sum += n; alt = !alt; } return sum % 10 === 0; };

// Does this look like something that must not be remembered?
function looksSecret(text) {
  const t = String(text || '').trim();
  if (!t) return false;
  if (/-----BEGIN [A-Z ]*PRIVATE KEY-----/.test(t)) return true;
  if (/\b(?:sk-[A-Za-z0-9_-]{16,}|sk_(?:live|test)_[A-Za-z0-9]{10,}|pk_live_[A-Za-z0-9]{10,}|gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|xox[abprs]-[A-Za-z0-9-]{10,}|AKIA[0-9A-Z]{16}|AIza[0-9A-Za-z_-]{30,}|eyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,})/.test(t)) return true;
  if (/\b(?:pass(?:word|wd|code)?|pwd|secret|token|api[_ -]?key|private[_ -]?key|pin)\b\s*(?:is|:|=)\s*\S+/i.test(t)) return true;
  if (/\b\d{3}-\d{2}-\d{4}\b/.test(t)) return true; // a social security number
  for (const m of t.matchAll(/\b(?:\d[ -]?){13,19}\b/g)) { const d = m[0].replace(/\D/g, ''); if (d.length >= 13 && d.length <= 19 && luhn(d)) return true; }
  // one word of 8 to 64 characters mixing cases, digits and symbols: what a generated password looks like (not a link, an address or a path)
  if (/^\S{8,64}$/.test(t) && !/^(?:https?:\/\/|www\.|[\w.+-]+@[\w-]+\.|[./~])/.test(t) && !/\.[a-z]{2,5}$/i.test(t)) {
    const classes = [/[a-z]/, /[A-Z]/, /\d/, /[^A-Za-z0-9]/].filter((r) => r.test(t)).length;
    if (classes >= 3 && /\d/.test(t)) return true;
  }
  return false;
}

class ClipboardHistory {
  // read(): { text, formats: [...] } (the clipboard now); getConfig(): { enabled, minutes }
  constructor({ read, getConfig = () => ({ enabled: true, minutes: 1440 }), now = Date.now, max = 60 }) {
    Object.assign(this, { read, getConfig, now, max });
    this.items = []; // newest first: { text, t }
    this.last = null; // the clipboard text last seen (so one copy is one entry)
    this.skipped = 0;
    this.ignored = new Set(); // text Relay itself put on the clipboard (typing, copying one back): not a copy by you
  }

  ignore(text) { this.ignored.add(String(text)); if (this.ignored.size > 20) this.ignored.delete(this.ignored.values().next().value); }

  // Looks at the clipboard: call about once a second.
  tick() {
    const cfg = this.getConfig() || {};
    this.prune(cfg);
    if (cfg.enabled === false) { this.last = null; return false; }
    let c;
    try { c = this.read(); } catch { return false; }
    const text = c && typeof c.text === 'string' ? c.text : '';
    if (!text.trim() || text === this.last) return false;
    this.last = text;
    if (this.ignored.has(text)) { this.ignored.delete(text); return false; }
    if ((c.formats || []).some((f) => CONCEALED.includes(f))) { this.skipped++; return false; }
    if (looksSecret(text)) { this.skipped++; return false; }
    this.items = [{ text: text.slice(0, 5000), t: this.now() }, ...this.items.filter((i) => i.text !== text.slice(0, 5000))].slice(0, this.max);
    return true;
  }

  prune(cfg = this.getConfig() || {}) {
    const ttl = Math.max(1, Number(cfg.minutes) || 1440) * 60000;
    const cutoff = this.now() - ttl;
    this.items = this.items.filter((i) => i.t >= cutoff);
  }

  list(n = 10) { return this.items.slice(0, n); }
  get(i) { return this.items[i] || null; }

  // The newest entry that has every word, or the one from about this long ago (minutes).
  find(query) {
    const words = String(query || '').toLowerCase().split(/\s+/).filter((w) => w.length > 1 && !['the', 'one', 'about', 'with', 'that', 'copied', 'link', 'text'].includes(w));
    if (!words.length) return null;
    return this.items.find((i) => words.every((w) => i.text.toLowerCase().includes(w))) || null;
  }

  ago(minutes) {
    const target = this.now() - minutes * 60000;
    let best = null;
    for (const i of this.items) if (!best || Math.abs(i.t - target) < Math.abs(best.t - target)) best = i;
    return best && Math.abs(best.t - target) <= Math.max(5, minutes * 0.5) * 60000 ? best : null;
  }

  clear() { const n = this.items.length; this.items = []; this.last = null; return n; }
}

const ORD = { first: 1, second: 2, third: 3, fourth: 4, fifth: 5, last: 1, previous: 2, '1st': 1, '2nd': 2, '3rd': 3, '4th': 4, '5th': 5 };
const NUM = { one: 1, two: 2, three: 3, four: 4, five: 5, ten: 10, fifteen: 15, twenty: 20, thirty: 30, forty: 40, sixty: 60, an: 1, a: 1 };

// Returns { type: 'clip-list' | 'clip-ago' | 'clip-find' | 'clip-copy' | 'clip-paste' | 'clip-clear' | 'clip-on' | 'clip-off', … } or null.
function parseClipboardCommand(text) {
  const n = String(text || '').toLowerCase().replace(/[.!?,]+/g, ' ').replace(/\s+/g, ' ').trim().replace(/^(?:hey |ok |okay )?(?:relay|jarvis) /, '').replace(/^please /, '').replace(/ please$/, '');
  let m;
  if (/^(?:turn|switch) (on|off)(?: my| the)? clipboard history$|^(?:start|stop) (?:recording|keeping|saving)(?: my| the)? clipboard(?: history)?$/.test(n)) return { type: /(?:turn|switch) off|stop/.test(n) ? 'clip-off' : 'clip-on' };
  if (/^(?:clear|delete|erase|forget|wipe)(?: all)?(?: of)?(?: my| the)? clipboard history$|^(?:clear|forget) what i(?: have)? copied$/.test(n)) return { type: 'clip-clear' };
  if (/^(?:show|list|what is in|what s in|read)(?: me)?(?: my| the)? clipboard history$|^what(?: did| have) i (?:copied|copy)(?: earlier| recently| lately| today| before)?$|^what have i copied(?: so far)?$|^what was(?: the thing)? i (?:copied|copying)(?: earlier| before)?$|^my clipboard history$/.test(n)) return { type: 'clip-list' };
  if ((m = n.match(/^what did i copy (an?|\d+|one|two|three|five|ten|fifteen|twenty|thirty|forty|sixty) (hour|hours|minute|minutes|min|mins) ago$/))) {
    const k = /^\d+$/.test(m[1]) ? +m[1] : NUM[m[1]] || 1;
    return { type: 'clip-ago', minutes: /^h/.test(m[2]) ? k * 60 : k };
  }
  if ((m = n.match(/^(?:copy|put|get|bring)(?: back)?(?: the)? (first|second|third|fourth|fifth|last|previous|1st|2nd|3rd|4th|5th)(?: one| thing| item| entry)?(?: i copied)?(?: back)?(?: to (?:my )?clipboard)?$/))) return { type: 'clip-copy', index: ORD[m[1]] };
  if ((m = n.match(/^paste(?: in)?(?: the)? (first|second|third|fourth|fifth|last|previous|1st|2nd|3rd|4th|5th)(?: one| thing| item| entry)?(?: i copied)?$/))) return { type: 'clip-paste', index: ORD[m[1]] };
  if ((m = n.match(/^(?:copy|paste|find|what was|where is|get)(?: back)?(?: the)? (?:one|thing|link|text|snippet|code) (?:about|with|containing|that (?:had|has|said|mentioned)|i copied about) (.+)$/)) || (m = n.match(/^what was the (?:link|text|thing|code) (?:i copied )?(?:about|with|containing) (.+)$/))) return { type: 'clip-find', query: m[1], paste: /^paste/.test(n) };
  return null;
}

module.exports = { ClipboardHistory, looksSecret, parseClipboardCommand, CONCEALED };
