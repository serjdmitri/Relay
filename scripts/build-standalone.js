#!/usr/bin/env node
// Builds the standalone Jarvis Navigation page: the same page the Mac serves to the phone, packaged as plain files that any web host can serve (for example GitHub Pages), so it works
// without the Mac and without a VPN. The phone page then asks the free map services directly (see src/remote/navdirect.js).
//
//   node scripts/build-standalone.js            writes ./standalone
//   node scripts/build-standalone.js --out DIR  writes DIR
//
// Nothing is uploaded or published by this script.
const fs = require('fs'), path = require('path');

const ROOT = path.join(__dirname, '..');
const FILES = ['navigation.js', 'navigation.css', 'navmath.js', 'navvoice.js', 'wakeword.js', 'navdirect.js', 'apple-touch-icon.png'];
const MAP_FILES = ['maplibre-gl.mjs', 'maplibre-gl-shared.mjs', 'maplibre-gl-worker.mjs', 'maplibre-gl.css'];

function page(html) {
  const must = (from, to) => { if (!html.includes(from)) throw Error('build-standalone: the page changed, update the build: ' + from.slice(0, 60)); html = html.replace(from, to); };
  must('<html lang="en">', '<html lang="en" data-standalone="1">');
  must("connect-src 'self' https: http://127.0.0.1:* http://localhost:*;", "connect-src 'self' https:;");
  must('<a id="back" href="/" aria-label="Back to Relay">← Relay</a>', '<a id="back" href="./" aria-label="Back to Relay" hidden>← Relay</a>'); // there is no Mac Relay to go back to
  must('<link rel="stylesheet" href="maplibre/maplibre-gl.css">', '<link rel="manifest" href="manifest.webmanifest"><link rel="apple-touch-icon" href="apple-touch-icon.png"><meta name="apple-mobile-web-app-capable" content="yes"><meta name="mobile-web-app-capable" content="yes"><meta name="apple-mobile-web-app-title" content="Jarvis Nav"><meta name="apple-mobile-web-app-status-bar-style" content="black-translucent"><link rel="stylesheet" href="maplibre/maplibre-gl.css">');
  return html;
}

function build(outDir = path.join(ROOT, 'standalone')) {
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(path.join(outDir, 'maplibre'), { recursive: true });
  const src = (f) => path.join(ROOT, 'src', 'remote', f);
  fs.writeFileSync(path.join(outDir, 'index.html'), page(fs.readFileSync(src('navigation.html'), 'utf8')));
  for (const f of FILES) fs.copyFileSync(src(f), path.join(outDir, f));
  const lib = path.join(ROOT, 'node_modules', 'maplibre-gl');
  for (const f of MAP_FILES) fs.copyFileSync(path.join(lib, 'dist', f), path.join(outDir, 'maplibre', f));
  fs.copyFileSync(path.join(lib, 'LICENSE.txt'), path.join(outDir, 'maplibre', 'LICENSE.txt'));
  fs.writeFileSync(path.join(outDir, 'manifest.webmanifest'), JSON.stringify({
    name: 'Jarvis Navigation', short_name: 'Jarvis Nav', start_url: './', scope: './', display: 'standalone', orientation: 'portrait',
    background_color: '#030a10', theme_color: '#030a10', icons: [{ src: 'apple-touch-icon.png', sizes: '180x180', type: 'image/png', purpose: 'any' }]
  }, null, 2) + '\n');
  fs.writeFileSync(path.join(outDir, 'README.txt'), 'Jarvis Navigation (standalone). Generated by scripts/build-standalone.js from src/remote; do not edit here.\nMap code: MapLibre GL JS (BSD-3-Clause, see maplibre/LICENSE.txt). Map data: OpenStreetMap contributors, OpenFreeMap, Photon, Valhalla / FOSSGIS.\n');
  return outDir;
}

module.exports = { build, page, FILES, MAP_FILES };

if (require.main === module) {
  const i = process.argv.indexOf('--out');
  const out = build(i > 0 ? path.resolve(process.argv[i + 1]) : undefined);
  console.log('Built the standalone page in ' + out);
}
